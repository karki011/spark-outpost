import { extensionOf } from './languages.ts';

export const MAX_FILE_BYTES = 512 * 1024;

const SKIPPED_DIRECTORIES = new Set([
  'node_modules',
  'vendor',
  'dist',
  'build',
  'out',
  'target',
  'coverage',
  '.git',
  '.next',
  '.nuxt',
  '.turbo',
  '.cache',
  '.yarn',
  '.venv',
  'venv',
  '__pycache__',
  '__snapshots__',
  'storybook-static',
  'bower_components',
]);

const LOCKFILES = new Set([
  'pnpm-lock.yaml',
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'bun.lockb',
  'bun.lock',
  'cargo.lock',
  'go.sum',
  'poetry.lock',
  'uv.lock',
  'pipfile.lock',
  'gemfile.lock',
  'composer.lock',
  'packages.lock.json',
]);

const BINARY_EXTENSIONS = new Set(
  (
    'png jpg jpeg gif bmp ico icns webp avif tiff psd svgz ' +
    'woff woff2 ttf otf eot ' +
    'zip gz tgz bz2 xz 7z rar tar jar war ear ' +
    'pdf doc docx xls xlsx ppt pptx ' +
    'mp3 mp4 m4a wav ogg flac webm mov avi mkv ' +
    'exe dll so dylib a o obj lib class pyc pyo wasm node bin dat db sqlite ' +
    'map snap'
  ).split(' '),
);

const GENERATED_NAME =
  /(?:\.min\.(?:js|css)|\.bundle\.js|\.generated\.\w+|\.pb\.go|_pb2\.py|\.g\.dart)$/i;

export function skipReason(path: string): string | null {
  const parts = path.split('/');
  const name = (parts.at(-1) ?? '').toLowerCase();
  if (parts.slice(0, -1).some((part) => SKIPPED_DIRECTORIES.has(part))) return 'directory';
  if (LOCKFILES.has(name)) return 'lockfile';
  if (GENERATED_NAME.test(name)) return 'generated';
  if (BINARY_EXTENSIONS.has(extensionOf(name))) return 'binary';
  return null;
}

const BULK_DATA = /(?:^|\/)(?:testdata|test-data|fixtures|__fixtures__|test-fixtures|baselines)\//i;

export function isBulkData(path: string): boolean {
  return BULK_DATA.test(path);
}

export function isSkipped(path: string): boolean {
  return skipReason(path) !== null;
}

const GENERATED_MARKER = /@generated|do not edit|auto-generated|autogenerated/i;

export function looksBinary(head: Uint8Array): boolean {
  return head.includes(0);
}

export function looksGenerated(text: string): boolean {
  return GENERATED_MARKER.test(text.slice(0, 1024));
}
